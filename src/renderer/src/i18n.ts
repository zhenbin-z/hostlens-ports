const messages: Record<Locale, Messages> = {
  en: english,
  ja: japanese,
  "zh-CN": simplifiedChinese,
};

export function detectLocale(languages = navigator.languages): Locale {
  for (const language of languages) {
    const normalized = language.toLowerCase();
    if (normalized.startsWith("ja")) return "ja";
    if (normalized.startsWith("zh")) return "zh-CN";
    if (normalized.startsWith("en")) return "en";
  }
  return "en";
}

export function loadLocale(): Locale {
  const stored = window.localStorage.getItem("hostlens.locale");
  if (stored === "en" || stored === "ja" || stored === "zh-CN") return stored;
  return detectLocale();
}

export function translate(
  locale: Locale,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  return Object.entries(values).reduce(
    (message, [name, value]) =>
      message.replaceAll(`{${name}}`, String(value)),
    messages[locale][key],
  );
}

export function localizeWarning(locale: Locale, warning: string): string {
  if (
    warning ===
    "Some process details are unavailable because the process exited or macOS restricted access."
  ) {
    return translate(locale, "partialDetails");
  }

  const sampleMatch = warning.match(
    /^Live scanning is not implemented for (.+); showing sample data\.$/,
  );
  if (sampleMatch) {
    return translate(locale, "sampleDataWarning", {
      platform: sampleMatch[1]!,
    });
  }

  if (
    warning.startsWith(
      "Service inspection failed without affecting port results:",
    )
  ) {
    return translate(locale, "serviceInspectionWarning");
  }

  if (
    warning.startsWith(
      "Network inspection failed without affecting port results:",
    )
  ) {
    return translate(locale, "networkInspectionWarning");
  }

  if (
    warning.startsWith(
      "Runtime inspection failed without affecting other results:",
    ) ||
    warning.includes(" package inventory ")
  ) {
    return translate(locale, "runtimeInspectionWarning");
  }

  const networkComponentMatch = warning.match(
    /^(.+) inspection was unavailable:/,
  );
  if (networkComponentMatch) {
    return translate(locale, "networkComponentWarning", {
      component: networkComponentMatch[1]!,
    });
  }

  const locationMatch = warning.match(/^Could not inspect (.+)\.$/);
  if (locationMatch) {
    return translate(locale, "serviceLocationWarning", {
      path: locationMatch[1]!,
    });
  }

  const plistMatch = warning.match(
    /^(\d+) configured launchd item\(s\) could not be parsed completely\.$/,
  );
  if (plistMatch) {
    return translate(locale, "servicePlistWarning", {
      count: plistMatch[1]!,
    });
  }

  return warning;
}

